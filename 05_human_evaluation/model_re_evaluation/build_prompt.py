import json
from pathlib import Path

# ======================
# 配置区域
# ======================
INPUT_JSONL = "inputs.jsonl"      # 原始jsonl，每行是一个JSON
OUTPUT_JSONL = "prompts.jsonl"   # 生成后的prompt文件

PROMPT_TEMPLATE = """# Role
You are a Senior Data Quality Specialist and AI Logic Evaluator. Your expertise lies in evaluating synthetic data generated for LLM training, focusing on alignment, accuracy, complexity, and educational value.

# Context
I am generating a dataset for manufacturing and industrial scenarios. I have a JSON entry containing:
1. "target_scenario": The specific industrial situation.
2. "target_task": The specific task to be performed within that scenario.
3. "generated_response": The content generated by an LLM (which usually implies a question/problem and a corresponding solution/answer).

# Objective
Your task is to critically evaluate the specific JSON entry provided below based on four distinct dimensions.

# Evaluation Criteria
1. **Alignment (Scenario & Task):** Does the generated content strictly adhere to the defined "target_scenario" and "target_task"? Is it relevant to the domain?
2. **Correctness & Logic:** Is the answer/solution provided in the generated response factually correct and logically consistent with the question posed?
3. **Data Quality:** Is this a high-quality example? Is it non-trivial, challenging, and valuable for training a model? (Avoid generic or overly simple QA).
4. **Improvement Strategy:** If the data is flawed or mediocre, provide specific actionable instructions on how to rewrite it to reach a "Gold Standard" level.

# Input Data
Please evaluate the following JSON entry:
<input_json>
{{INSERT_YOUR_JSON_HERE}}
</input_json>

# Instructions
1. Analyze the `target_scenario` and `target_task` to understand the intent.
2. Read the `generated_response` carefully.
3. Think step-by-step for each of the 4 evaluation criteria.
4. Output your final evaluation in the strict JSON format defined below.

# Output Format
You must output a single valid JSON object with no markdown formatting (no ```json ... ``` blocks). The JSON schema is:

{
  "alignment_score": (integer 1-5),
  "alignment_comment": "Brief analysis of scenario/task alignment.",
  "correctness_score": (integer 1-5),
  "correctness_comment": "Analysis of the answer's accuracy.",
  "quality_score": (integer 1-5),
  "quality_comment": "Evaluation of the data's complexity and value.",
  "is_perfect": (boolean),
  "suggestions": {
    "direction": "Which specific aspect needs change (e.g., 'Increase complexity', 'Fix logic error', 'Narrow domain scope').",
    "rewrite_instruction": "Specific instruction on how to modify the prompt or the response to improve it."
  },
  "overall_reasoning": "A concise summary of why you gave these scores."
}
"""


def main():
    input_path = Path(INPUT_JSONL)
    output_path = Path(OUTPUT_JSONL)

    with input_path.open("r", encoding="utf-8") as fin, \
         output_path.open("w", encoding="utf-8") as fout:

        for line_idx, line in enumerate(fin):
            line = line.strip()
            if not line:
                continue

            try:
                data = json.loads(line)
            except json.JSONDecodeError as e:
                print(f"[WARN] Line {line_idx} JSON decode failed: {e}")
                continue

            # 将JSON美化为字符串，嵌入prompt
            json_str = json.dumps(data, ensure_ascii=False, indent=2)

            prompt = PROMPT_TEMPLATE.replace(
                "{{INSERT_YOUR_JSON_HERE}}",
                json_str
            )

            fout.write(
                json.dumps(
                    {"prompt": prompt},
                    ensure_ascii=False
                ) + "\n"
            )

    print(f"Done. Prompts saved to: {output_path}")


if __name__ == "__main__":
    main()
